def infer_fields(text: str) -> list[int]:
    """Return likely HGPF fields for a passage without changing its source wording."""
    scores: dict[int, int] = {}
    for keyword, field_ids in KEYWORD_TO_FIELDS.items():
        if keyword in text:
            for field_id in field_ids:
                scores[field_id] = scores.get(field_id, 0) + 1
    return [field_id for field_id, _ in sorted(scores.items(), key=lambda pair: (-pair[1], pair[0]))[:6]]
